# arithmetic.py - Python as a calculator
print(1200 + 350)        # addition
print(1200 - 350)        # subtraction
print(1200 * 3)          # multiplication
print(1200 / 7)          # division always gives a float
print(1.045 ** 2)        # power: 1.045 squared
print(30 // 12)          # floor division: whole years
print(30 % 12)           # remainder: months left over
print(2 + 3 * 4)         # multiplication first
print((2 + 3) * 4)       # brackets first
